"""Build fastgrib/tables/satellites.py: the satellites (BUFR table
0 01 007) and instruments (0 02 019) wgrib2 names a simulated or observed
satellite product's spectral bands by (its sat= inventory item,
Spectral_bands.c), from wgrib2's own copies of those tables (public
domain).

    python tools/tables/make_satellites.py WGRIB2_DIR

WGRIB2_DIR  wgrib2's source directory holding BUFRTable_0_01_007.dat and
            BUFRTable_0_02_019.dat (https://github.com/NOAA-EMC/wgrib2,
            v3.2.0: the same names as 3.1.3 gives)
"""
import os
import re
import sys


def satellites(path):
    s = open(path, encoding='latin-1').read()
    return {int(k): v for k, v in re.findall(r'case\s+(\d+):\s*satellite="([^"]*)"', s)}


def instruments(path):
    s = open(path, encoding='latin-1').read()
    out = {}
    for k, body in re.findall(r'case\s+(\d+):(.*?)break;', s, re.S):
        m = re.search(r'shortname="([^"]*)"', body)
        if m:
            out[int(k)] = m.group(1)
    return out


def main(src):
    sat = satellites(os.path.join(src, 'BUFRTable_0_01_007.dat'))
    ins = instruments(os.path.join(src, 'BUFRTable_0_02_019.dat'))
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, '..', '..', 'fastgrib', 'tables', 'satellites.py')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('"""Satellites (BUFR table 0 01 007) and instruments (0 02 019, their\n'
                'short names) as wgrib2 names a satellite product\'s spectral bands.\n'
                'Generated by tools/tables/make_satellites.py from wgrib2\'s tables\n'
                '(public domain); do not edit. Neither listed: \'Unknown\', as wgrib2."""\n\n')
        f.write('SATELLITES = {\n')
        for k in sorted(sat):
            f.write('    %d: %r,\n' % (k, sat[k]))
        f.write('}\n\nINSTRUMENTS = {\n')
        for k in sorted(ins):
            f.write('    %d: %r,\n' % (k, ins[k]))
        f.write('}\n')
    print('%d satellites, %d instruments -> %s' % (len(sat), len(ins), os.path.normpath(out)))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
