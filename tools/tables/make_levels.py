"""Build fastgrib/tables/levels.py: code table 4.5 as wgrib2 words it (its
Level.c, public domain: the WMO levels, and NCEP's and KMA's local ones)
and as ecCodes names it (typeOfLevelConcept.def, (C) ECMWF, Apache
License 2.0 -- see fastgrib/NOTICE).

    python tools/tables/make_levels.py LEVEL_C DEFINITIONS_DIR

LEVEL_C          wgrib2's src/Level.c (https://github.com/NOAA-EMC/wgrib2, develop)
DEFINITIONS_DIR  ecCodes' definitions directory (2.50.0): its grib2/
                 typeOfLevelConcept.def and localConcepts/kwbc/'s (NCEP's)

Names that hang on a level's value (ecCodes' cloud layers between given
pressures, hPa against Pa) are left out: a level type keeps one name.
"""
import os
import re
import sys


def tables(path):
    s = open(path, encoding='latin-1').read()
    out = {}
    for name, body in re.findall(r'const char \*(\w+)\[\d*\]\s*=\s*\{(.*?)\};', s, re.S):
        ents = re.findall(r'/\*\s*(\d+)\s*\*/\s*"((?:[^"\\]|\\.)*)"', body)
        out[name] = [v for _, v in sorted((int(k), v) for k, v in ents)]
    return out


def kinds(path):
    """{(first type, second type or None): typeOfLevel}, the last match of
    each pair as ecCodes' get returns it."""
    text = re.sub(r'#[^\n]*', '', open(path, encoding='utf-8').read())
    out = {}
    for val, body in re.findall(r"'([^']*)'\s*=\s*\{(.*?)\}", text, re.S):
        d = dict((k, v.strip()) for k, v in re.findall(r'(\w+)\s*=\s*([^;]+);', body))
        if any(not k.startswith('typeOf') and v != 'missing()' for k, v in d.items()):
            continue
        t1, t2 = d.get('typeOfFirstFixedSurface'), d.get('typeOfSecondFixedSurface')
        if t1 is None or not t1.isdigit() or (t2 is not None and not t2.isdigit()):
            continue
        out[(int(t1), None if t2 is None else int(t2))] = val
    return out


def main(level_c, defs):
    t = tables(level_c)
    wmo, ncep, kma = t['level_table'], t['ncep_level_table'], t['kma_level_table']
    assert (len(wmo), len(ncep), len(kma)) == (192, 64, 64)
    k = kinds(os.path.join(defs, 'grib2', 'typeOfLevelConcept.def'))
    k[(100, 255)] = 'isobaricInhPa'             # whatever the value (ecCodes: hPa or Pa)
    kn = kinds(os.path.join(defs, 'grib2', 'localConcepts', 'kwbc', 'typeOfLevelConcept.def'))
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'fastgrib', 'tables', 'levels.py')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('"""Code table 4.5: wgrib2\'s wording of each level type (from its Level.c,\n'
                'public domain) -- WMO, the WMO levels; NCEP, KMA, their local levels from\n'
                '192 -- and ecCodes\' typeOfLevel names, KINDS: (first type, second type or\n'
                'None) -> name, KINDS_NCEP NCEP\'s (ecCodes 2.50.0, (C) ECMWF, Apache License\n'
                '2.0, see NOTICE). Generated by tools/tables/make_levels.py; do not edit."""\n\n')
        for name, tab in (('WMO', wmo), ('NCEP', ncep), ('KMA', kma)):
            f.write('%s = (\n' % name)
            for v in tab:
                f.write('    %r,\n' % v)
            f.write(')\n\n')
        for name, kk in (('KINDS', k), ('KINDS_NCEP', kn)):
            f.write('%s = {\n' % name)
            for key in sorted(kk, key=lambda x: (x[0], -1 if x[1] is None else x[1])):
                f.write('    %r: %r,\n' % (key, kk[key]))
            f.write('}\n\n')
    print('%d + %d + %d level wordings, %d level names -> %s'
          % (len(wmo), len(ncep), len(kma), len(k) + len(kn), os.path.normpath(out)))


if __name__ == '__main__':
    main(*sys.argv[1:3])
