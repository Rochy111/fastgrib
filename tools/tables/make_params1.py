"""Build fastgrib/tables/params1.py: NCEP's GRIB1 parameter tables (ON388 Table 2
and its local tables 128-141: number -> abbreviation, description, units),
each parameter with its GRIB2 numbers where NCEP's GRIB2 table (_params.py)
has the same abbreviation -- the GRIB1 field then reads as the GRIB2 one.
NCEP's pages are a US government work (public domain).

    python tools/tables/make_params1.py TABLE2_HTML

TABLE2_HTML: https://www.nco.ncep.noaa.gov/pmb/docs/on388/table2.html
"""
import html
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
from fastgrib.tables.params import PARAMS         # noqa: E402
from fastgrib._grib1 import RENAMED         # noqa: E402


def cell(x):
    x = re.sub(r'\s*<su[pb]>\s*(.*?)\s*</su[pb]>', r'\1', x, flags=re.S | re.I)
    x = html.unescape(re.sub(r'<[^>]+>', ' ', x))
    return ' '.join(x.split())


def main(page):
    s = open(page, encoding='latin-1').read()
    # each table follows its anchor: <a name="TABLE2">, <a name="TABLE128">, ...
    marks = [(m.start(), int(m.group(1))) for m in re.finditer(r'name="TABLE(\d+)"', s)]
    marks.append((len(s), None))
    by_name = {}
    for (d, c, n), (name, desc, units) in sorted(PARAMS.items()):
        by_name.setdefault(name, (d, c, n))
    tab, linked = {}, 0
    for (a, ver), (b, _) in zip(marks, marks[1:]):
        for r in re.findall(r'<tr[^>]*>(.*?)</tr>', s[a:b], re.S | re.I):
            cells = [cell(x) for x in re.findall(r'<t[dh][^>]*>(.*?)</t[dh]>', r, re.S | re.I)]
            if len(cells) < 4 or not cells[0].isdigit():
                continue
            num, desc, units, name = int(cells[0]), cells[1], cells[2], cells[3]
            if not name or name in ('-', 'var') or 'reserved' in desc.lower():
                continue
            desc = re.sub(r'\s*\((see )?notes? [\d, and]+\)', '', desc, flags=re.I).strip()
            g2 = by_name.get(name) or by_name.get(RENAMED.get(name))
            linked += g2 is not None
            tab[(ver, num)] = (name, desc, units, g2)
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'fastgrib', 'tables', 'params1.py')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('"""NCEP\'s GRIB1 parameter tables (ON388 Table 2, local tables 128-141):\n'
                '(table version, number) -> (name, description, units, GRIB2 (discipline,\n'
                'category, number) of the same name or None). Generated by\n'
                'tools/tables/make_params1.py from NCEP\'s ON388 documentation (public domain);\n'
                'do not edit."""\n\n')
        f.write('PARAMS1 = {\n')
        for k in sorted(tab):
            f.write('    %r: %r,\n' % (k, tab[k]))
        f.write('}\n')
    print('%d GRIB1 parameters (%d tables), %d with GRIB2 numbers -> %s'
          % (len(tab), len({k[0] for k in tab}), linked, os.path.normpath(out)))


if __name__ == '__main__':
    main(sys.argv[1])
