"""Build fastgrib/tables/params.py from NCEP's GRIB2 documentation: code table
4.2 (parameter number by product discipline and category), one page per
discipline and category, with NCEP's short names, descriptions and units.
NCEP's pages are a US government work (public domain).

    python tools/tables/make_params.py PAGES_DIR

PAGES_DIR holds the pages, fetched from
https://www.nco.ncep.noaa.gov/pmb/docs/grib2/grib2_doc/grib2_table4-2.shtml
(each grib2_table4-2-D-C.shtml it links to).
"""
import glob
import html
import os
import re
import sys


# deprecated parameters NCEP's pages leave unnamed, by the names NCEP's
# products (NAM's soil moisture) and wgrib2 still give them
DEPRECATED = {(2, 0, 3): ('SOILM', 'Soil Moisture Content', 'kg m-2'),
              (2, 0, 22): ('SOIL_M', 'Soil Moisture', 'kg m-3')}


def cell(x):
    x = re.sub(r'\s*<su[pb]>\s*(.*?)\s*</su[pb]>', r'\1', x, flags=re.S | re.I)   # m<sup>-2</sup> -> m-2
    x = html.unescape(re.sub(r'<[^>]+>', ' ', x))
    return ' '.join(x.split())


def main(pages):
    tab = {}
    for p in sorted(glob.glob(os.path.join(pages, 'grib2_table4-2-*.shtml'))):
        d, c = map(int, re.findall(r'4-2-(\d+)-(\d+)', p)[0])
        s = open(p, encoding='latin-1').read()
        for r in re.findall(r'<tr[^>]*>(.*?)</tr>', s, re.S | re.I):
            cells = [cell(x) for x in re.findall(r'<td[^>]*>(.*?)</td>', r, re.S | re.I)]
            if len(cells) < 4 or not cells[0].isdigit() or not cells[3] or cells[3] == '-':
                continue
            desc = re.sub(r'\s*\((see )?notes? [\d, and]+\)', '', cells[1], flags=re.I).strip()
            tab[(d, c, int(cells[0]))] = (cells[3], desc, cells[2])
    for k, v in DEPRECATED.items():
        tab.setdefault(k, v)
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'fastgrib', 'tables',
                       'params.py')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('"""GRIB2 code table 4.2 with NCEP\'s short names: (discipline, category,\n'
                'number) -> (name, description, units). Generated by tools/tables/make_params.py\n'
                'from NCEP\'s GRIB2 documentation (public domain); do not edit."""\n\n')
        f.write('PARAMS = {\n')
        for k in sorted(tab):
            f.write('    %r: %r,\n' % (k, tab[k]))
        f.write('}\n')
    print('%d parameters -> %s' % (len(tab), os.path.normpath(out)))


if __name__ == '__main__':
    main(sys.argv[1])
