"""Build fastgrib/tables/chem.py: GRIB2 code table 4.230 (atmospheric chemical
constituent and aerosol types -- WMO Common Code table C-14), from WMO's
own CSV (https://github.com/wmo-im/CCT, C14.csv; MIT License).

    python tools/tables/make_chem.py C14.csv
"""
import csv
import os
import sys


def main(path):
    names = {}
    for row in csv.DictReader(open(path, encoding='utf-8-sig')):
        code = row['CodeFigure'].strip()
        if code.isdigit():
            names[int(code)] = row['Meaning_en'].strip()
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'fastgrib', 'tables', 'chem.py')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('"""GRIB2 code table 4.230 (WMO Common Code table C-14): constituent and\n'
                'aerosol types. Generated by tools/tables/make_chem.py from WMO\'s C14.csv\n'
                '(github.com/wmo-im/CCT, MIT License); do not edit."""\n\n')
        f.write('CONSTITUENTS = {\n')
        for k in sorted(names):
            f.write('    %d: %r,\n' % (k, names[k]))
        f.write('}\n')
    print('%d constituent types -> %s' % (len(names), os.path.normpath(out)))


if __name__ == '__main__':
    main(sys.argv[1])
