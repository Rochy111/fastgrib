"""Build fastgrib/tables/params1_ecmwf.py: ECMWF's GRIB1 parameters by ecCodes'
definitions (2.50.0, (C) ECMWF, Apache License 2.0 -- see NOTICE): (table
version, number) -> (shortName, name, units, GRIB2 (discipline, category,
number) of the same paramId or None, and that GRIB2 concept's level and
statistic or None), for the concepts that hang on the table and number
alone. GRIB1 leaves those to the parameter (2t on the 'surface', at 2 m by
its number); GRIB2 says them.

    python tools/tables/make_params1_ecmwf.py DEFINITIONS_DIR
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_eccodes import concepts           # noqa: E402

IMPLIED = ('typeOfFirstFixedSurface', 'scaleFactorOfFirstFixedSurface',
           'scaledValueOfFirstFixedSurface', 'typeOfSecondFixedSurface',
           'scaleFactorOfSecondFixedSurface', 'scaledValueOfSecondFixedSurface',
           'typeOfStatisticalProcessing')


def plain(rows, keys=('table2Version', 'indicatorOfParameter')):
    """{(table, number): value} of the concepts keyed on those alone."""
    out = {}
    for val, c in rows:
        if c is None:
            continue
        d = dict(c)
        if set(d) == set(keys):
            out.setdefault(tuple(d[k] for k in keys), val)
    return out


def _best(dcn, val, c):
    """dcn[paramId]: the GRIB2 concept with the fewest conditions."""
    if c is None:
        return
    d = dict(c)
    if not all(k in d for k in ('discipline', 'parameterCategory', 'parameterNumber')):
        return
    k = (d['discipline'], d['parameterCategory'], d['parameterNumber'])
    if val not in dcn or len(d) < dcn[val][1]:
        dcn[val] = (k, len(d), tuple((x, d[x]) for x in IMPLIED if x in d) or None)


def main(defs):
    g1, g2 = os.path.join(defs, 'grib1'), os.path.join(defs, 'grib2')
    names = {}
    for kind in ('shortName', 'name', 'units', 'paramId'):
        merged = {}
        for path in (os.path.join(g1, 'localConcepts', 'ecmf', kind + '.def'),
                     os.path.join(g1, kind + '.def')):
            if os.path.exists(path):
                for k, v in plain(concepts(path)).items():
                    merged.setdefault(k, v)
        names[kind] = merged
    # GRIB2's numbers of each paramId: its concept with the fewest conditions
    # (then, for paramIds those lack, the older encodings of tables version 33 and before:
    # 'since the previous post-processing' parameters with numbers of their own)
    dcn = {}
    for older in ('', '.lte33'):
        known = set(dcn)
        for path in (os.path.join(g2, 'paramId%s.def' % older),
                     os.path.join(g2, 'localConcepts', 'ecmf', 'paramId%s.def' % older)):
            for val, c in concepts(path):
                if val not in known:
                    _best(dcn, val, c)
    tab = {}
    for key, short in names['shortName'].items():
        pid = names['paramId'].get(key)
        g2n, _, implied = dcn.get(pid, (None, 0, None))
        tab[key] = (short, names['name'].get(key, 'unknown'), names['units'].get(key, 'unknown'),
                    g2n, implied)
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'fastgrib', 'tables',
                       'params1_ecmwf.py')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('"""ECMWF\'s GRIB1 parameters: (table version, number) -> (shortName,\n'
                'name, units, GRIB2 (discipline, category, number) or None, its GRIB2\n'
                'level and statistic ((key, value), ...) or None). Generated by\n'
                'tools/tables/make_params1_ecmwf.py from ecCodes 2.50.0\'s definitions, (C) ECMWF,\n'
                'Apache License 2.0 (see NOTICE); do not edit."""\n\n')
        f.write('PARAMS1_EC = {\n')
        for k in sorted(tab):
            f.write('    %r: %r,\n' % (k, tab[k]))
        f.write('}\n')
    print('%d ECMWF GRIB1 parameters, %d with GRIB2 numbers -> %s'
          % (len(tab), sum(v[3] is not None for v in tab.values()), os.path.normpath(out)))


if __name__ == '__main__':
    main(sys.argv[1])
