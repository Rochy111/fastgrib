"""Build fastgrib/tables/eccodes.py from ecCodes' GRIB2 definitions: the
parameter concepts (shortName, name, units) of the WMO tables and of
ECMWF's local ones, each in its current form and the form for tables
version 33 and before (ecCodes' 'lte33' files), NCEP's local ones and the
legacy ones (retired numbers).
ecCodes is (C) ECMWF, Apache License 2.0 (see fastgrib/NOTICE).

    python tools/tables/make_eccodes.py DEFINITIONS_DIR

DEFINITIONS_DIR is ecCodes' definitions directory (ecCodes 2.50.0 here:
https://github.com/ecmwf/eccodes/tree/2.50.0/definitions).

Only concepts whose conditions fastgrib can evaluate are kept (chemistry,
aerosol, wavelength, random-field and reference-period ones are not).
"""
import os
import re
import sys

# what fastgrib evaluates of a field, in the order its key tuples hold
KEYS = ('discipline', 'parameterCategory', 'parameterNumber',
        'typeOfFirstFixedSurface', 'scaleFactorOfFirstFixedSurface',
        'scaledValueOfFirstFixedSurface', 'typeOfSecondFixedSurface',
        'scaleFactorOfSecondFixedSurface', 'scaledValueOfSecondFixedSurface',
        'typeOfStatisticalProcessing', 'lengthOfTimeRange', 'indicatorOfUnitForTimeRange',
        'localTablesVersion', 'typeOfGeneratingProcess', 'probabilityType',
        'scaleFactorOfLowerLimit', 'scaledValueOfLowerLimit',
        'productDefinitionTemplateNumber',
        # chemicals and aerosols (4.40-4.49): what, its size, its wavelength, which kind
        'constituentType', 'aerosolType', 'typeOfSizeInterval', 'scaleFactorOfFirstSize',
        'scaledValueOfFirstSize', 'scaleFactorOfSecondSize', 'scaledValueOfSecondSize',
        'typeOfWavelengthInterval', 'scaleFactorOfFirstWavelength',
        'scaledValueOfFirstWavelength', 'scaleFactorOfSecondWavelength',
        'scaledValueOfSecondWavelength', 'is_chemical', 'is_chemical_distfn',
        'is_chemical_srcsink', 'is_aerosol', 'is_aerosol_optical',
        'gridDefinitionTemplateNumber')
MISSING = -1
# the concept sets: bit 1 the WMO tables, 2 WMO for tables version <= 33,
# 4 ECMWF's, 8 ECMWF's for tables version <= 33, 16 NCEP's, 32 and 64 the
# legacy WMO and ECMWF ones (retired numbers: ecCodes' last resort), 128 and
# 256 the WMO and ECMWF ones of the parameter-and-chemical split (a chemical
# or aerosol as its kind of quantity, 'aod': fastgrib's last resort, as
# ecCodes before 2.49 named these)
SETS = ((1, 'shortName.def'), (2, 'shortName.lte33.def'),
        (4, 'localConcepts/ecmf/shortName.def'), (8, 'localConcepts/ecmf/shortName.lte33.def'),
        (16, 'localConcepts/kwbc/shortName.def'), (32, 'shortName.legacy.def'),
        (64, 'localConcepts/ecmf/shortName.legacy.def'), (128, 'shortName.chemsplit.def'),
        (256, 'localConcepts/ecmf/shortName.chemsplit.def'))


def concepts(path):
    """[(value, ((key, value), ...))] of a concept file, in its order;
    None where a condition is not a plain value."""
    text = re.sub(r'#[^\n]*', '', open(path, encoding='utf-8').read())
    out = []
    for val, body in re.findall(r"'([^']*)'\s*=\s*\{(.*?)\}", text, re.S):
        conds = []
        for k, v in re.findall(r'(\w+)\s*=\s*([^;]+);', body):
            v = v.strip()
            if v == 'missing()':
                conds.append((k, MISSING))
            elif re.match(r'^-?\d+$', v):
                conds.append((k, int(v)))
            else:
                conds = None
                break
        out.append((val, None if conds is None else tuple(conds)))
    return out


def main(defs):
    g2 = os.path.join(defs, 'grib2')
    table = {}                                  # (d, c, n) -> {(short, name, units, conds): sets}
    for bit, rel in SETS:
        short = concepts(os.path.join(g2, rel))
        name = concepts(os.path.join(g2, rel.replace('shortName', 'name')))
        units = concepts(os.path.join(g2, rel.replace('shortName', 'units')))
        assert len(short) == len(name) == len(units), rel
        for (s, c), (n, c2), (u, c3) in zip(short, name, units):
            assert c == c2 == c3, (rel, s)
            if c is None or any(k not in KEYS for k, _ in c):
                continue
            d = dict(c)
            if not all(k in d for k in KEYS[:3]):
                continue
            rest = tuple(sorted((KEYS.index(k), v) for k, v in c if k not in KEYS[:3]))
            key = (d['discipline'], d['parameterCategory'], d['parameterNumber'])
            e = (s, n, u, rest)
            table.setdefault(key, {})
            table[key][e] = table[key].get(e, 0) | bit
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'fastgrib', 'tables',
                       'eccodes.py')
    n = 0
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('"""ecCodes\' GRIB2 parameter concepts. Generated by tools/tables/make_eccodes.py\n'
                'from the definitions of ecCodes 2.50.0, (C) ECMWF, Apache License 2.0\n'
                '(see NOTICE); do not edit.\n\n'
                'CONCEPTS: (discipline, category, number) -> ((shortName, name, units,\n'
                'sets, ((key index, value), ...)), ...), most conditions first, key\n'
                'indices into KEYS, MISSING for missing(); sets: 1 WMO, 2 WMO for tables\n'
                'version <= 33, 4 ECMWF, 8 ECMWF for tables version <= 33, 16 NCEP,\n'
                '32 WMO legacy, 64 ECMWF legacy, 128 WMO and 256 ECMWF chemical split."""\n\n')
        f.write('KEYS = %r\n' % (KEYS,))
        f.write('MISSING = %d\n\n' % MISSING)
        f.write('CONCEPTS = {\n')
        for key in sorted(table):
            ents = sorted(table[key].items(), key=lambda kv: -len(kv[0][3]))   # stable
            f.write('    %r: (\n' % (key,))
            for (s, nm, u, rest), sets in ents:
                f.write('        (%r, %r, %r, %d, %r),\n' % (s, nm, u, sets, rest))
                n += 1
            f.write('    ),\n')
        f.write('}\n')
    print('%d concepts of %d parameters -> %s' % (n, len(table), os.path.normpath(out)))


if __name__ == '__main__':
    main(sys.argv[1])
